// Invoice creation and PDF (a simple invoice/receipt for micro & small sellers).
import fs from 'node:fs';
import path from 'node:path';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { config } from '../config.js';
import { getDb, nextId, save, round2 } from '../store.js';
import { addDays, todayIso, prettyDate } from '../clock.js';
import { connect } from '../orbyte/index.js';

const rm = (n) => `RM ${Number(n).toFixed(2)}`;

export async function createInvoice(order, customer) {
  const db = getDb();
  const issueDate = todayIso();
  const terms = customer.paymentTermsDays || 0;
  const invoice = {
    id: nextId('invoice', 'INV-'),
    orderId: order.id,
    customerId: customer.id,
    issueDate,
    dueDate: addDays(issueDate, terms),
    deliveryDate: order.deliveryDate,
    lines: order.lines.map(({ sku, name, unit, qty, unitPrice, amount }) => ({ sku, name, unit, qty, unitPrice, amount })),
    total: round2(order.total),
    status: 'unpaid',
    paidAt: null,
    remindersSent: [],
  };
  invoice.paymentUrl = connect.payments.createLink(invoice);
  const file = await renderPdf(invoice, customer, db.business);
  invoice.pdfFile = file;
  invoice.pdfUrl = `${config.baseUrl}/invoices/${path.basename(file)}`;
  db.invoices.push(invoice);
  save();
  return invoice;
}

// Standard PDF fonts only know Latin-1-ish characters; replace the rest.
const safe = (s) => String(s ?? '').replace(/[^\x20-\x7E -ÿ–—‘’“”]/g, '?');

export async function renderPdf(invoice, customer, business) {
  const dir = path.join(config.dataDir, 'invoices');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${invoice.id}.pdf`);

  const pdf = await PDFDocument.create();
  pdf.setTitle(`Invoice ${invoice.id}`);
  pdf.setProducer('OrderLah prototype');
  const page = pdf.addPage([595.28, 841.89]); // A4
  const H = page.getHeight();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.12, 0.14, 0.16);
  const quiet = rgb(0.35, 0.39, 0.43);
  const accent = rgb(0.04, 0.48, 0.36);
  const rule = rgb(0.89, 0.91, 0.92);
  const L = 48;
  const R = 595.28 - 48;

  const text = (s, x, yTop, { size = 10, font = regular, color = ink, align = 'left' } = {}) => {
    const str = safe(s);
    const w = font.widthOfTextAtSize(str, size);
    const dx = align === 'right' ? x - w : align === 'center' ? x - w / 2 : x;
    page.drawText(str, { x: dx, y: H - yTop - size, size, font, color });
  };

  // header
  text(business.name, L, 48, { size: 18, font: bold, color: accent });
  text(`${business.address}  |  Tel +${business.phone}`, L, 72, { size: 9, color: quiet });
  text(`BRN ${business.brn}`, L, 85, { size: 9, color: quiet });

  text('INVOICE', R, 120, { size: 15, font: bold, align: 'right' });
  [`No: ${invoice.id}`, `Date: ${invoice.issueDate}`, `Due: ${invoice.dueDate}`, `Order: ${invoice.orderId}`]
    .forEach((s, i) => text(s, R, 142 + i * 14, { size: 10, color: quiet, align: 'right' }));

  text('BILL TO', L, 122, { size: 8.5, color: quiet });
  text(customer.name, L, 136, { size: 12, font: bold });
  text(`+${customer.phone}`, L, 154, { size: 10, color: quiet });
  text(`Delivery: ${prettyDate(invoice.deliveryDate)}`, L, 168, { size: 10, color: quiet });

  // table
  let y = 220;
  page.drawRectangle({ x: L, y: H - y - 22, width: R - L, height: 22, color: rgb(0.93, 0.96, 0.95) });
  text('Item', L + 8, y + 6, { font: bold });
  text('Qty', 350, y + 6, { font: bold, align: 'right' });
  text('Price', 440, y + 6, { font: bold, align: 'right' });
  text('Amount', R - 8, y + 6, { font: bold, align: 'right' });
  y += 32;
  for (const l of invoice.lines) {
    text(l.name, L + 8, y);
    text(`${l.qty} ${l.unit}`, 350, y, { align: 'right' });
    text(rm(l.unitPrice), 440, y, { align: 'right' });
    text(rm(l.amount), R - 8, y, { align: 'right' });
    y += 20;
    page.drawLine({ start: { x: L, y: H - y + 4 }, end: { x: R, y: H - y + 4 }, thickness: 0.5, color: rule });
  }
  y += 10;
  text(`TOTAL   ${rm(invoice.total)}`, R - 8, y, { size: 13, font: bold, align: 'right' });

  // payment
  y += 50;
  page.drawRectangle({ x: L, y: H - y - 70, width: R - L, height: 70, borderColor: accent, borderWidth: 1, color: rgb(0.96, 0.99, 0.97) });
  text('Pay', L + 14, y + 12, { size: 11, font: bold });
  text('Open this link to pay with DuitNow / FPX:', L + 14, y + 30, { size: 9.5, color: quiet });
  text(invoice.paymentUrl, L + 14, y + 44, { size: 10, font: bold, color: accent });
  text(business.bank, R - 14, y + 12, { size: 9, color: quiet, align: 'right' });

  // footer
  text('Generated by OrderLah on Orbyte (hackathon prototype)', 595.28 / 2, H - 70, { size: 7.5, color: quiet, align: 'center' });

  fs.writeFileSync(file, await pdf.save());
  return file;
}
